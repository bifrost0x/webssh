const {test,expect}=require('playwright/test');
const {login}=require('./helpers');
for(const width of [390,768,1440]) test(`dashboard editing and repeated reset preserve layout at ${width}`,async({page},info)=>{
 await page.route('**/api/automation/runs',r=>r.fulfill({json:{runs:[{id:'layout-run',name:'Inventory',created_at:new Date().toISOString(),status:'succeeded',targets:[]}]}}));
 await page.setViewportSize({width,height:740});await login(page,'e2e_admin',{workspace:false});
 await expect(page.locator('#connectionOverview')).toHaveAttribute('data-dashboard-default','true');
 const map=page.locator('[data-module=infrastructure]');
 await page.locator('#overviewCustomize').click();
 await expect(page.locator('#connectionOverview')).toHaveAttribute('data-dashboard-default','false');
 await map.getByRole('button',{name:'Move later',exact:true}).click();
 await map.getByLabel('Infrastructure width').selectOption('full');
 await map.getByLabel('List height').selectOption('compact');
 await page.locator('#overviewCustomize').click();
 const saved=await page.evaluate(()=>localStorage.getItem('webssh:dashboard:'+document.querySelector('meta[name=background-scope]').content));
 await page.locator('#overviewResetDashboard').click();await page.locator('#overviewResetDashboard').click();
 await page.locator('#overviewUndoDashboard').click();
 expect(await page.evaluate(()=>localStorage.getItem('webssh:dashboard:'+document.querySelector('meta[name=background-scope]').content))).toBe(saved);
 await page.locator('#overviewResetDashboard').click();
 await page.locator('#overviewCustomize').click();
 await map.getByRole('checkbox',{name:'Show',exact:true}).uncheck();
 await page.locator('#overviewCustomize').click();await expect(map).toBeHidden();
 await expect(page.locator('#connectionOverview')).toHaveAttribute('data-dashboard-default','false');
 await page.reload();await page.waitForFunction(()=>ProfileManager.profilesLoaded);await expect(map).toBeHidden();
 await page.locator('#overviewResetDashboard').click();await expect(map).toBeVisible();
 await expect(page.locator('#connectionOverview')).toHaveAttribute('data-dashboard-default','true');
 for(const next of [3440,390,width]) { await page.setViewportSize({width:next,height:740});
 expect(await page.locator('#connectionOverview').evaluate(e=>e.scrollWidth<=e.clientWidth+1)).toBe(true); }
 await page.locator('#overviewCustomize').click();
 const controls=map.locator('.overview-module-tools');
 expect(await controls.evaluate(e=>e.scrollWidth<=e.clientWidth+1)).toBe(true);
 await page.screenshot({path:info.outputPath(`editing-${width}.png`),animations:'disabled'});
 await page.locator('#overviewCustomize').click();
 await page.locator('#overviewAnalytics').scrollIntoViewIfNeeded();
 await expect(page.locator('#overviewAnalytics select')).toHaveValue('7');
 await page.locator('#overviewAnalytics select').selectOption('14');
 await page.locator('#overviewCustomize').click();
 await map.getByLabel('List height').selectOption('large');
 await page.locator('#overviewCustomize').click();
 await expect(page.locator('#overviewAnalytics select')).toHaveValue('14');
 await page.locator('#overviewAnalytics').scrollIntoViewIfNeeded();
 expect((await page.locator('#overviewAnalytics select').boundingBox()).width).toBeGreaterThanOrEqual(84);
 await page.screenshot({path:info.outputPath(`activity-${width}.png`),animations:'disabled'});
});
