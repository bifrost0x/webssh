const {test, expect}=require('playwright/test');
const {login, installSshConnectTrap, assertNoExternalRequests}=require('./helpers');
const path=require('node:path');
const fs=require('node:fs');
test.afterEach(async({page})=>assertNoExternalRequests(page));
for(const width of [1440,390]) {
 test(`presets and recovery remain explicit and usable at ${width}px`,async({page})=>{
    await page.setViewportSize({width,height:900});
    await login(page);
    await installSshConnectTrap(page);
    let presets=[];
    await page.route('**/api/account/workspace-presets',route=>{if(route.request().method()==='PUT')presets=route.request().postDataJSON().presets;return route.fulfill({json:{presets}});});
    const folder=path.join(process.cwd(),'plans','presets-recovery-refinement');fs.mkdirSync(folder,{recursive:true});
    await expect(page.locator('#accountDropdownHeader [data-workspace-presets]')).toHaveCount(0);
    const layout=page.locator('#workspaceLayoutPicker > summary');
    await layout.click();
    const entry=page.locator('#workspaceLayoutPicker #workspacePresetsBtn');
    await expect(entry).toBeVisible();
    await expect(entry).toHaveAccessibleName('Workspace presets');
    const entryBounds=await entry.boundingBox();
    expect(entryBounds.x).toBeGreaterThanOrEqual(0);expect(entryBounds.x+entryBounds.width).toBeLessThanOrEqual(width);
    await page.screenshot({path:path.join(folder,`workspace-entry-${width}.png`),fullPage:true});
    await entry.click();
    let dialog=page.getByRole('dialog');
    await expect(dialog.getByText('No presets yet. Save a layout and host selection below.')).toBeVisible();
    await dialog.getByLabel('Preset name',{exact:true}).fill('Daily operations');
    await dialog.getByLabel('Panes',{exact:true}).selectOption('2');
    await dialog.getByLabel('Password review',{exact:true}).check();
    await dialog.getByRole('button',{name:'Save preset',exact:true}).click();
    await expect(dialog.getByRole('status')).toHaveText('Preset saved.');
    await expect(dialog.getByRole('button',{name:'Connect Password review',exact:true})).toBeHidden();
    await dialog.getByRole('button',{name:'Apply layout and choose connections',exact:true}).click();
    await expect(dialog.getByRole('button',{name:'Connect Password review',exact:true})).toBeVisible();
    expect(await page.evaluate(()=>window.__sshConnectAttempts.length)).toBe(0);
    expect(await dialog.evaluate(node=>node.scrollWidth<=node.clientWidth)).toBe(true);
    await page.screenshot({path:path.join(folder,`presets-${width}.png`),fullPage:true});
    await dialog.getByLabel('Preset name',{exact:true}).fill('Too many hosts');
    await dialog.getByLabel('Panes',{exact:true}).selectOption('1');
    await dialog.getByLabel('Ops first',{exact:true}).check();
    await dialog.locator('.customer-dialog-body').evaluate(node=>{node.scrollTop=node.scrollHeight;});
    await dialog.getByRole('button',{name:'Save preset',exact:true}).focus();
    await page.keyboard.press('Enter');
    const error=dialog.getByRole('alert');
    await expect(error).toHaveText('Choose no more hosts than the number of panes.');
    await expect(error).toBeFocused();
    const bounds=await error.boundingBox();const bodyBounds=await dialog.locator('.customer-dialog-body').boundingBox();
    expect(bounds.y).toBeGreaterThanOrEqual(bodyBounds.y);
    expect(bounds.y+bounds.height).toBeLessThanOrEqual(bodyBounds.y+bodyBounds.height+1);
    await dialog.getByRole('button',{name:'Close',exact:true}).click();
    await expect(layout).toBeFocused();
    await expect(page.locator('#workspaceLayoutPicker')).not.toHaveAttribute('open','');
    await page.route('**/api/account/recovery-check',route=>route.fulfill({json:{restored_at:'2026-11-14T08:00:00Z',needs_review:true,hosts:[{id:'synthetic-lab',name:'Lab server',credential:'key_required',route:'missing_jump',host_key:'review_required'}],schedules:[{name:'Inspect system health',enabled:false}]}}));
    await page.evaluate(()=>document.querySelector('[data-recovery-check]').click());
    dialog=page.getByRole('dialog');
    await expect(dialog.locator('.customer-checklist > li')).toHaveCount(4);
    await expect(dialog.getByText('SSH key required', {exact:false})).toBeVisible();
    await expect(dialog.locator('.customer-disclosure')).not.toHaveAttribute('open','');
    const ack=dialog.getByRole('button',{name:'Mark recovery steps reviewed'});
    await expect(ack).toBeVisible();
    await expect(ack).toHaveAttribute('aria-describedby','recoveryReviewHint');
    expect(await dialog.evaluate(node=>node.scrollWidth<=node.clientWidth)).toBe(true);
    await page.screenshot({path:path.join(folder,`recovery-${width}.png`),fullPage:true});
    await dialog.getByText('Backup coverage',{exact:true}).click();
    await expect(dialog.getByText(/Portable backups exclude/)).toBeVisible();
    await page.screenshot({path:path.join(folder,`recovery-details-${width}.png`),fullPage:true});
    await page.keyboard.press('Escape');
    await expect(dialog).toHaveCount(0);
    expect(await page.evaluate(()=>window.__sshConnectAttempts.length)).toBe(0);
 });
}
